import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cooksBySlug } from '../lib/cooks.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'content', 'transcripts');
const output = join(root, 'public', 'transcripts');
const kinds = ['biography', 'recipe'];
const languages = ['es', 'en'];
// Spanish-speaking visitors hear the recordings directly, so only the English translations are
// published for now. The Spanish transcripts stay in content/ as the source the English is checked
// against; add 'es' here to publish them again.
const publishedLanguages = ['en'];

// Riverside exports one "SPEAKER (mm:ss)" line per cue, then the spoken text.
// The speaker is always the studio, so only the timestamp is worth keeping.
const cueHeader = /^.*?\((\d{1,3}:\d{2}(?::\d{2})?)\)\s*$/;

function parse(raw) {
  const segments = [];
  let current = null;

  for (const line of raw.replace(/\r\n/g, '\n').split('\n')) {
    const text = line.trim();
    if (!text) {
      current = null;
      continue;
    }
    const header = text.match(cueHeader);
    if (header) {
      current = { time: header[1], text: '' };
      segments.push(current);
      continue;
    }
    if (!current) {
      current = { time: null, text: '' };
      segments.push(current);
    }
    current.text = current.text ? `${current.text} ${text}` : text;
  }

  return segments.filter((segment) => segment.text);
}

async function read(language, slug, kind) {
  try {
    return parse(await readFile(join(source, language, `${slug}.${kind}.txt`), 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

const files = (await Promise.all(languages.map((language) => readdir(join(source, language))))).flat();
const slugs = [...new Set(files.filter((file) => file.endsWith('.txt')).map((file) => file.split('.')[0]))].sort();

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });

const manifest = {};
const warnings = [];

for (const slug of slugs) {
  if (!cooksBySlug[slug]) {
    warnings.push(`no profile in lib/cooks.ts for transcript slug "${slug}"`);
    continue;
  }
  for (const kind of kinds) {
    const [es, en] = await Promise.all(languages.map((language) => read(language, slug, kind)));
    if (!es && !en) continue;
    if (es && en && es.length !== en.length) {
      warnings.push(
        `${slug}.${kind}: ${es.length} Spanish cues vs ${en.length} English — the English will not line up with the audio`,
      );
    }

    const available = { es, en };
    const missing = publishedLanguages.filter((language) => !available[language]);
    if (missing.length) {
      warnings.push(`${slug}.${kind} is not published: no ${missing.join(' or ')} transcript`);
      continue;
    }
    const transcript = Object.fromEntries(publishedLanguages.map((language) => [language, available[language]]));

    await writeFile(join(output, `${slug}.${kind}.json`), `${JSON.stringify(transcript)}\n`);
    (manifest[slug] ??= []).push(kind);
  }
}

const generated = `// Generated by scripts/build-transcripts.mjs from content/transcripts/. Do not edit by hand.
import type { AudioTrack, Language } from './cooks';

export const transcriptLanguages: Language[] = ${JSON.stringify(publishedLanguages)};

export const transcriptManifest: Record<string, AudioTrack['kind'][]> = ${JSON.stringify(manifest, null, 2)};

export function hasTranscript(slug: string, kind: AudioTrack['kind'], language: Language): boolean {
  return transcriptLanguages.includes(language) && (transcriptManifest[slug]?.includes(kind) ?? false);
}
`;
await writeFile(join(root, 'lib', 'transcript-manifest.ts'), generated);

for (const warning of warnings) console.warn(`warning: ${warning}`);
const count = Object.values(manifest).reduce((total, list) => total + list.length, 0);
console.log(`Built ${count} transcripts for ${Object.keys(manifest).length} cocineras into public/transcripts/.`);
